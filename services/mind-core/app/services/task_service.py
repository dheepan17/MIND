"""TaskService — business boundary for the ``tasks`` table (Phase 4.5).

This is the task-lifecycle service boundary. It owns validation,
existence checks, and audit integration, but contains no SQL and never
creates a connection or commits/rolls back — the caller owns the
transaction (see :class:`app.services.base.BaseService`).

Authorization boundary
----------------------
The current capability catalog defines no task-lifecycle capability
(e.g. ``task:create`` / ``task:assign``). Following the same pattern as
``AgentService`` (Phase 4.4), this service does NOT gate task operations
on a capability. When such capabilities are introduced, callers can
compose ``PermissionService.require_capability(...)`` inside their
transaction, or this service can be extended to require them — no schema
change is needed. We deliberately do not invent a ``task:*`` capability
here.

Cycle safety
------------
The schema's self-referential ``parent_task_id`` FK does not prevent
cycles. However, the contract exposes no reparent operation; a task's
parent is fixed at creation, and the new task's id is generated by the
database (``gen_random_uuid()``), so a task can never be its own ancestor
at creation time. The only parent-related invariant enforced here is
existence: a ``parent_task_id`` must reference a real task. (If a future
phase adds reparenting, ancestor-cycle detection via ``list_subtree``
belongs here.)
"""
from __future__ import annotations

import uuid

from app.repositories.agents import AgentRepository
from app.repositories.tasks import TaskRepository
from app.services.audit_service import AuditService
from app.services.base import BaseService
from app.services.errors import AuthorizationError, NotFoundError, ValidationError
from app.services.permission_service import PermissionService

_VALID_STATUSES = (
    "pending",
    "running",
    "completed",
    "failed",
    "blocked",
    "cancelled",
)
_VALID_ACTOR_TYPES = ("agent", "human", "role")
_MAX_LIMIT = 100


def _is_uuid(value: str) -> bool:
    try:
        uuid.UUID(str(value))
        return True
    except (ValueError, TypeError, AttributeError):
        return False


class TaskService(BaseService):
    """Business boundary for task lifecycle operations."""

    def __init__(self, conn) -> None:
        super().__init__(conn)
        # PermissionService shares this service's connection and therefore the
        # caller's transaction. It owns the generic ``write`` capability check
        # (Phase 5.8).
        self._perms = PermissionService(conn)

    # ── authorization helpers (Phase 5.8) ───────────────────
    def _require_write(self, actor_id: str) -> None:
        """Gate a mutation on the generic ``write`` capability.

        ``actor_id`` is the trusted ``SecurityContext.actor_id`` supplied by the
        router — never a client-supplied body/query field. Raises
        :class:`AuthorizationError` (HTTP 403) when the capability is absent.
        """
        self._perms.require_write(actor_id)

    def _audit_denied(
        self,
        *,
        actor_type: str,
        actor_id: str,
        action: str,
        target_id: str | None,
    ) -> None:
        """Record a denied task mutation (missing/insufficient capability)."""
        AuditService(self._conn).record(
            actor_type=actor_type,
            actor_id=actor_id,
            action=action,
            outcome="denied",
            target_type="task",
            target_id=target_id,
            capability_used="write",
        )

    # ── helpers ───────────────────────────────────────────
    def _require_task(self, task_id: str) -> dict:
        task = self.repository(TaskRepository).get(task_id)
        if task is None:
            raise NotFoundError(f"Task '{task_id}' does not exist.")
        return task

    def _require_agent(self, agent_id: str) -> None:
        if self.repository(AgentRepository).get(agent_id) is None:
            raise NotFoundError(f"Agent '{agent_id}' does not exist.")

    @staticmethod
    def _validate_paging(limit: int, offset: int) -> None:
        if not isinstance(limit, int) or isinstance(limit, bool):
            raise ValidationError("limit must be an int.")
        if limit < 1 or limit > _MAX_LIMIT:
            raise ValidationError(f"limit must be between 1 and {_MAX_LIMIT}.")
        if not isinstance(offset, int) or isinstance(offset, bool):
            raise ValidationError("offset must be an int.")
        if offset < 0:
            raise ValidationError("offset must be >= 0.")

    def _audit(
        self,
        *,
        actor_type: str,
        actor_id: str | None,
        action: str,
        target_id: str | None,
        context: dict | None = None,
    ) -> None:
        # AuditService validates actor_type/outcome and persists on the
        # same caller-owned connection. Never raises for a missing
        # actor_id (the column is NOT NULL but the caller is responsible
        # for supplying it; we pass it through unchanged).
        AuditService(self._conn).record(
            actor_type=actor_type,
            actor_id=actor_id,
            action=action,
            outcome="success",
            target_type="task",
            target_id=target_id,
            context=context,
        )

    # ── 1. create ─────────────────────────────────────────
    def create(
        self,
        *,
        title: str,
        actor_id: str,
        actor_type: str = "agent",
        agent_id: str | None = None,
        status: str = "pending",
        priority: int = 5,
        parent_task_id: str | None = None,
        description: str | None = None,
        input_payload: object | None = None,
        metadata: object | None = None,
    ) -> dict:
        if not isinstance(title, str) or not title.strip():
            raise ValidationError("title must be a non-empty string.")
        if actor_type not in _VALID_ACTOR_TYPES:
            raise ValidationError(
                f"actor_type must be one of {_VALID_ACTOR_TYPES}."
            )
        if status not in _VALID_STATUSES:
            raise ValidationError(
                f"status must be one of {_VALID_STATUSES}; got {status!r}."
            )
        if not isinstance(priority, int) or isinstance(priority, bool):
            raise ValidationError("priority must be an int.")
        if agent_id is not None and not _is_uuid(agent_id):
            raise ValidationError("agent_id must be a valid UUID.")
        if parent_task_id is not None and not _is_uuid(parent_task_id):
            raise ValidationError("parent_task_id must be a valid UUID.")

        # Existence checks (do not rely on raw FK errors for user input).
        if agent_id is not None:
            self._require_agent(agent_id)
        if parent_task_id is not None:
            # A task can never be its own parent at creation (id is
            # DB-generated), so self-parent rejection is implicit; we only
            # need to confirm the referenced parent exists.
            self._require_task(parent_task_id)

        # Authorization occurs inside the transaction, before the mutation.
        try:
            self._require_write(actor_id)
        except AuthorizationError:
            self._audit_denied(
                actor_type=actor_type,
                actor_id=actor_id,
                action="task.create",
                target_id=None,
            )
            raise

        task = self.repository(TaskRepository).create(
            agent_id=agent_id,
            title=title,
            status=status,
            priority=priority,
            parent_task_id=parent_task_id,
            description=description,
            input_payload=input_payload,
            metadata=metadata,
        )
        self._audit(
            actor_type=actor_type,
            actor_id=actor_id,
            action="task.create",
            target_id=str(task["id"]),
            context={"status": status, "priority": priority},
        )
        return task

    # ── 2. get ────────────────────────────────────────────
    def get(self, task_id: str) -> dict:
        if not _is_uuid(task_id):
            raise ValidationError("task_id must be a valid UUID.")
        return self._require_task(task_id)

    # ── 3. update_status ──────────────────────────────────
    def update_status(
        self,
        task_id: str,
        status: str,
        *,
        actor_id: str,
        actor_type: str = "agent",
    ) -> dict:
        if not _is_uuid(task_id):
            raise ValidationError("task_id must be a valid UUID.")
        if status not in _VALID_STATUSES:
            raise ValidationError(
                f"status must be one of {_VALID_STATUSES}; got {status!r}."
            )
        if actor_type not in _VALID_ACTOR_TYPES:
            raise ValidationError(
                f"actor_type must be one of {_VALID_ACTOR_TYPES}."
            )
        self._require_task(task_id)
        # Authorization occurs inside the transaction, before the mutation.
        try:
            self._require_write(actor_id)
        except AuthorizationError:
            self._audit_denied(
                actor_type=actor_type,
                actor_id=actor_id,
                action="task.update_status",
                target_id=task_id,
            )
            raise
        self.repository(TaskRepository).update_status(task_id, status)
        # completed_at is owned by the repository (set on completion).
        self._audit(
            actor_type=actor_type,
            actor_id=actor_id,
            action="task.update_status",
            target_id=task_id,
            context={"status": status},
        )
        return self._require_task(task_id)

    # ── 4. assign_agent ───────────────────────────────────
    def assign_agent(
        self,
        task_id: str,
        agent_id: str | None,
        *,
        actor_id: str,
        actor_type: str = "agent",
    ) -> dict:
        if not _is_uuid(task_id):
            raise ValidationError("task_id must be a valid UUID.")
        if agent_id is not None and not _is_uuid(agent_id):
            raise ValidationError("agent_id must be a valid UUID.")
        if actor_type not in _VALID_ACTOR_TYPES:
            raise ValidationError(
                f"actor_type must be one of {_VALID_ACTOR_TYPES}."
            )
        self._require_task(task_id)
        if agent_id is not None:
            self._require_agent(agent_id)
        # Authorization occurs inside the transaction, before the mutation.
        try:
            self._require_write(actor_id)
        except AuthorizationError:
            self._audit_denied(
                actor_type=actor_type,
                actor_id=actor_id,
                action="task.assign_agent",
                target_id=task_id,
            )
            raise
        # No resource-scoped capability is invented; the generic ``write``
        # capability (checked above) gates this mutation.
        self.repository(TaskRepository).assign_agent(task_id, agent_id)
        self._audit(
            actor_type=actor_type,
            actor_id=actor_id,
            action="task.assign_agent",
            target_id=task_id,
            context={"agent_id": str(agent_id) if agent_id else None},
        )
        return self._require_task(task_id)

    # ── 5. list_children ──────────────────────────────────
    def list_children(
        self, parent_task_id: str, *, limit: int = 50, offset: int = 0
    ) -> list[dict]:
        if not _is_uuid(parent_task_id):
            raise ValidationError("parent_task_id must be a valid UUID.")
        self._validate_paging(limit, offset)
        return self.repository(TaskRepository).list_children(
            parent_task_id, limit=limit, offset=offset
        )

    # ── 6. list_by_agent ──────────────────────────────────
    def list_by_agent(
        self, agent_id: str, *, limit: int = 50, offset: int = 0
    ) -> list[dict]:
        if not _is_uuid(agent_id):
            raise ValidationError("agent_id must be a valid UUID.")
        self._validate_paging(limit, offset)
        return self.repository(TaskRepository).list_by_agent(
            agent_id, limit=limit, offset=offset
        )

    # ── 7. list_by_status ─────────────────────────────────
    def list_by_status(
        self, status: str, *, limit: int = 50, offset: int = 0
    ) -> list[dict]:
        if status not in _VALID_STATUSES:
            raise ValidationError(
                f"status must be one of {_VALID_STATUSES}; got {status!r}."
            )
        self._validate_paging(limit, offset)
        return self.repository(TaskRepository).list_by_status(
            status, limit=limit, offset=offset
        )

    # ── 8. list_subtree ───────────────────────────────────
    def list_subtree(self, root_task_id: str, *, limit: int = 100) -> list[dict]:
        if not _is_uuid(root_task_id):
            raise ValidationError("root_task_id must be a valid UUID.")
        if not isinstance(limit, int) or isinstance(limit, bool) or limit < 1:
            raise ValidationError("limit must be an int >= 1.")
        return self.repository(TaskRepository).list_subtree(
            root_task_id, limit=limit
        )